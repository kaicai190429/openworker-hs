    /// Writes one memory; HeliconSearch answers `{memory_id, action}`.
    pub(crate) async fn store(&self, req: Value) -> HsResult<(String, StoreStatus)> {
        let raw = self
            .call(
                Method::POST,
                "/v1/memory/store",
                Some(req),
                None,
                None,
                &CallOptions::default(),
            )
            .await?;
        let id = raw
            .get("memory_id")
            .and_then(Value::as_str)
            .ok_or_else(|| HsError::Malformed("store answered without a memory_id".into()))?
            .to_owned();
        let status = if raw.get("action").and_then(Value::as_str) == Some("created") {
            StoreStatus::Created
        } else {
            StoreStatus::Dedupe
        };
        Ok((id, status))
    }

    /// The operator: extracts facts from archived messages. Not retried and given a long timeout; a 202
    /// that hands over no work unit is not an acceptance (the caller must resend).
    pub(crate) async fn add(&self, req: Value) -> HsResult<AddResult> {
        let path = "/v1/memory/add";
        let session = req
            .get("session_id")
            .and_then(Value::as_str)
            .unwrap_or("?")
            .to_owned();
        let (status, text) = self
            .exchange(
                &Method::POST,
                path,
                Some(&req),
                OPERATOR_TIMEOUT_MS,
                &CallOptions::default(),
            )
            .await?;
        if !status.is_success() {
            return Err(self.api_error(&Method::POST, path, status.as_u16(), &text));
        }
        let raw: Value = serde_json::from_str(&text).map_err(|e| {
            HsError::Malformed(format!(
                "helicon-memory POST {path}: answer is not JSON: {e}"
            ))
        })?;
        let code = raw.get("code").and_then(Value::as_i64).unwrap_or(200);
        let numbers = |key: &str| -> Vec<i64> {
            raw.get(key)
                .and_then(Value::as_array)
                .map(|a| a.iter().filter_map(Value::as_i64).collect())
                .unwrap_or_default()
        };
        let mut result = AddResult {
            archive_mismatched: numbers("archive_mismatched"),
            not_archived: numbers("not_archived"),
            archive_conflicts: numbers("archive_conflicts"),
            ..Default::default()
        };
        let work_unit = raw.get("work_unit_id").and_then(Value::as_str);
        if code == 202 && raw.get("queued") == Some(&Value::Bool(true)) && work_unit.is_some() {
            self.inner.logger.info(&format!(
                "{TAG} /v1/memory/add queued as work unit {} session={session} - the server finishes it",
                work_unit.unwrap_or("")
            ));
            result.queued = true;
            result.work_unit_id = work_unit.map(str::to_owned);
            return Ok(result);
        }
        if code == 202 {
            self.inner.logger.warn(&format!(
                "{TAG} /v1/memory/add 202 work-unit already in flight session={session} - not accepted, will retry"
            ));
            return Err(HsError::Api {
                status: status.as_u16(),
                retcode: Some(202),
                retmsg: Some("work-unit already in flight".into()),
                message: format!(
                    "helicon-memory POST {path} not accepted: code=202 work-unit already in flight"
                ),
            });
        }
        if code >= 400 {
            let msg = raw
                .get("message")
                .and_then(Value::as_str)
                .map(str::to_owned)
                .unwrap_or_else(|| format!("code={code}"));
            self.log_failure(&Method::POST, path, status.as_u16(), &msg);
            return Err(HsError::Api {
                status: status.as_u16(),
                retcode: None,
                retmsg: Some(msg.clone()),
                message: format!("helicon-memory POST {path} failed: code={code} {msg}"),
            });
        }
        result.operations = raw
            .get("data")
            .and_then(Value::as_array)
            .cloned()
            .unwrap_or_default();
        result.already_processed = raw.get("already_processed") == Some(&Value::Bool(true));
        result.processing_state = raw
            .get("audit")
            .and_then(|a| a.get("processing"))
            .and_then(|p| p.get("state"))
            .and_then(Value::as_str)
            .map(str::to_owned);
        result.work_unit_id = work_unit.map(str::to_owned);
        Ok(result)
    }

    /// The organized recall view. Sent once, with the longer recall timeout unless `opts` sets a deadline.
    pub(crate) async fn query(&self, req: Value, opts: &CallOptions) -> HsResult<Value> {
        self.call(
            Method::POST,
            "/v1/memory/query",
            Some(req),
            Some(RECALL_TIMEOUT_MS),
            Some(1),
            opts,
        )
        .await
    }

    /// The SKILL.md body of a published skill.
    pub(crate) async fn get_skill(&self, skill_id: &str) -> HsResult<Option<String>> {
        let path = format!("/v1/memory/skill/{}", Self::enc(skill_id));
        match self
            .call(
                Method::GET,
                &path,
                None,
                None,
                None,
                &CallOptions::default(),
            )
            .await
        {
            Ok(v) => Ok(Some(
                v.get("content")
                    .and_then(Value::as_str)
                    .unwrap_or("")
                    .to_owned(),
            )),
            Err(e) if e.is_not_found() => Ok(None),
            Err(e) => Err(e),
        }
    }

    /// Soft-deletes a memory; `false` when HeliconSearch says nothing was deleted.
    pub(crate) async fn delete(&self, memory_id: &str) -> HsResult<bool> {
        let path = format!("/v1/memory/{}", Self::enc(memory_id));
        let data = self
            .call(
                Method::DELETE,
                &path,
                None,
                None,
                None,
                &CallOptions::default(),
            )
            .await?;
        Ok(data.get("deleted") == Some(&Value::Bool(true)))
    }

    pub(crate) async fn explain(&self, memory_id: &str) -> HsResult<Option<Value>> {
        let path = format!(
            "/v1/memory/explain?{}",
            Self::q(&[("memory_id", memory_id.to_owned())])
        );
        match self
            .call(
                Method::GET,
                &path,
                None,
                None,
                None,
                &CallOptions::default(),
            )
            .await
        {
            Ok(v) => Ok(Some(v)),
            Err(e) if e.is_not_found() => Ok(None),
            Err(e) => Err(e),
        }
    }

